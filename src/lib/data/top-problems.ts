/** Filters the discovery set by search text and a broad category group. */
export function searchProblems(query: string, filter: "All" | ProblemFilter): TopProblem[] {
  const q = query.trim().toLowerCase();
  return topProblems.filter((p) => {
    if (filter !== "All" && p.filter !== filter) return false;
    if (!q) return true;
    const haystack = [p.title, p.category, p.platform ?? "", p.shortContext ?? "", ...p.tags]
      .join(" ")
      .toLowerCase();
    return haystack.includes(q);
  });
}

/** The discovery set split by marquee row (stable, grouped order preserved). */
export function problemsByRow(row: ProblemRow): TopProblem[] {
  return topProblems.filter((p) => p.row === row);
}

/** Maps the broad discovery filter to the diagnosis wizard category. */
export function filterToDiagnosisCategory(
  filter: ProblemFilter
): "Coding Error" | "Windows / OS" | "Network & Wi-Fi" | "Hardware & Devices" | "Apps & Productivity" {
  switch (filter) {
    case "Coding":
    case "Development Tools":
      return "Coding Error";
    case "System":
      return "Windows / OS";
    case "Network":
      return "Network & Wi-Fi";
    case "Device":
      return "Hardware & Devices";
    case "Productivity":
      return "Apps & Productivity";
  }
}