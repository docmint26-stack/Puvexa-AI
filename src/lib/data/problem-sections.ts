/** Inclusive PUV id range helper: ids(1, 10) → PUV-0001 … PUV-0010 */
function ids(from: number, to: number): string[] {
  return Array.from({ length: to - from + 1 }, (_, i) => `PUV-${String(from + i).padStart(4, "0")}`);
}

function x(...nums: number[]): string[] {
  return nums.map((n) => `PUV-${String(n).padStart(4, "0")}`);
}

